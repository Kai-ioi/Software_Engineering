CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  display_name VARCHAR(100) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  platform_admin BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE course (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  semester VARCHAR(40) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  status VARCHAR(24) NOT NULL
);
CREATE TABLE course_membership (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  role VARCHAR(16) NOT NULL CHECK (role IN ('TEACHER', 'STUDENT', 'TA')),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_course_user UNIQUE (course_id, user_id)
);
CREATE INDEX idx_membership_user ON course_membership(user_id, active);
CREATE TABLE audit_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL REFERENCES app_user(id),
  course_id BIGINT NOT NULL REFERENCES course(id),
  action VARCHAR(80) NOT NULL,
  object_id VARCHAR(80) NOT NULL,
  summary VARCHAR(500) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_course_time ON audit_record(course_id, occurred_at);
CREATE TABLE stored_file (
  id UUID PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  owner_id BIGINT NOT NULL REFERENCES app_user(id),
  original_name VARCHAR(240) NOT NULL,
  extension VARCHAR(12) NOT NULL,
  size_bytes BIGINT NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 52428800),
  sha256 VARCHAR(64) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_file_owner_course ON stored_file(owner_id, course_id);
