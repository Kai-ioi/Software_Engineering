CREATE TABLE workflow_notice (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key VARCHAR(160) NOT NULL,
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 course_id BIGINT NOT NULL REFERENCES course(id),
 title VARCHAR(240) NOT NULL,
 href VARCHAR(240) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 read_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(event_key,user_id)
);
CREATE INDEX idx_workflow_notice_user ON workflow_notice(user_id,created_at);

CREATE TABLE project_change (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES course_project(id),
 actor_id BIGINT NOT NULL REFERENCES app_user(id),
 summary VARCHAR(240) NOT NULL,
 before_title VARCHAR(240) NOT NULL,
 after_title VARCHAR(240) NOT NULL,
 before_description TEXT NOT NULL,
 after_description TEXT NOT NULL,
 before_deadline TIMESTAMP WITH TIME ZONE,
 after_deadline TIMESTAMP WITH TIME ZONE,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_project_change_project ON project_change(project_id,id);

