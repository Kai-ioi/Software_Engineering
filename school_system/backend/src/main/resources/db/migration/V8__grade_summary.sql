-- Module D (module 8): grade summary, roster snapshot, publish, correction and export.
-- Final score = teacher_total * teacher_weight + peer_total * peer_weight (default 70/30).
-- Peer source comes from module C's review_submission (pinned to the same review binding).

ALTER TABLE grading_rubric ADD COLUMN IF NOT EXISTS teacher_weight INTEGER NOT NULL DEFAULT 70 CHECK (teacher_weight >= 0 AND teacher_weight <= 100);
ALTER TABLE grading_rubric ADD COLUMN IF NOT EXISTS peer_weight INTEGER NOT NULL DEFAULT 30 CHECK (peer_weight >= 0 AND peer_weight <= 100);
CREATE TABLE grade_roster (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES project_team(id),
  rubric_id BIGINT NOT NULL REFERENCES grading_rubric(id),
  member_ids TEXT NOT NULL,
  confirmed_by BIGINT NOT NULL REFERENCES app_user(id),
  confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(team_id)
);

CREATE TABLE grade_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  team_id BIGINT NOT NULL REFERENCES project_team(id),
  rubric_id BIGINT NOT NULL REFERENCES grading_rubric(id),
  sheet_id BIGINT NOT NULL REFERENCES grading_sheet(id),
  roster_id BIGINT NOT NULL REFERENCES grade_roster(id),
  teacher_total NUMERIC(6,2) NOT NULL,
  peer_total NUMERIC(6,2) NOT NULL,
  final_total NUMERIC(6,2) NOT NULL,
  teacher_weight INTEGER NOT NULL CHECK (teacher_weight >= 0 AND teacher_weight <= 100),
  peer_weight INTEGER NOT NULL CHECK (peer_weight >= 0 AND peer_weight <= 100),
  status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED','CORRECTED')),
  version_no INTEGER NOT NULL CHECK (version_no > 0),
  parent_id BIGINT REFERENCES grade_result(id),
  correction_reason VARCHAR(2000),
  published_by BIGINT NOT NULL REFERENCES app_user(id),
  published_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(team_id, version_no)
);
CREATE INDEX idx_grade_result_team ON grade_result(team_id, id);

CREATE TABLE grade_member_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id BIGINT NOT NULL REFERENCES grade_result(id),
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  final_total NUMERIC(6,2) NOT NULL
);
CREATE INDEX idx_grade_member_user ON grade_member_result(user_id, result_id);
