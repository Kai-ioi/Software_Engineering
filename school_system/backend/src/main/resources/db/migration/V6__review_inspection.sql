-- Module 5: peer review. Reviews are pinned to the teacher-confirmed
-- submission_review_binding (an immutable evaluated version), never to the
-- mutable current version. Reviewer identity is hidden from the reviewed team.
CREATE TABLE review_round (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES course_project(id),
 name VARCHAR(160) NOT NULL,
 deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
 feedback_open BOOLEAN NOT NULL DEFAULT FALSE,
 created_by BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_review_round_project ON review_round(project_id,id);

CREATE TABLE review_task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 round_id BIGINT NOT NULL REFERENCES review_round(id),
 binding_id BIGINT NOT NULL REFERENCES submission_review_binding(id),
 reviewer_id BIGINT NOT NULL REFERENCES app_user(id),
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SUBMITTED','CANCELLED')),
 reevaluation BOOLEAN NOT NULL DEFAULT FALSE,
 assigned_by BIGINT NOT NULL REFERENCES app_user(id),
 assigned_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_review_task_round ON review_task(round_id,status);
CREATE INDEX idx_review_task_reviewer ON review_task(reviewer_id,status);

CREATE TABLE review_submission (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id BIGINT NOT NULL UNIQUE REFERENCES review_task(id),
 binding_id BIGINT NOT NULL REFERENCES submission_review_binding(id),
 reviewer_id BIGINT NOT NULL REFERENCES app_user(id),
 score INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),
 comment VARCHAR(2000) NOT NULL,
 submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE review_appeal (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 round_id BIGINT NOT NULL REFERENCES review_round(id),
 binding_id BIGINT NOT NULL REFERENCES submission_review_binding(id),
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 requested_by BIGINT NOT NULL REFERENCES app_user(id),
 reason VARCHAR(2000) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
 resolved_by BIGINT REFERENCES app_user(id),
 resolved_at TIMESTAMP WITH TIME ZONE,
 resolution VARCHAR(2000)
);

-- Module 6: TA process inspection. Each check is pinned to a specific version;
-- a recheck references the earlier inspection via parent_id.
CREATE TABLE inspection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 version_id BIGINT NOT NULL REFERENCES submission_version(id),
 checker_id BIGINT NOT NULL REFERENCES app_user(id),
 conclusion VARCHAR(2000) NOT NULL,
 feedback VARCHAR(2000),
 rectification_required BOOLEAN NOT NULL DEFAULT FALSE,
 reported BOOLEAN NOT NULL DEFAULT FALSE,
 checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
 parent_id BIGINT REFERENCES inspection(id)
);
CREATE INDEX idx_inspection_team ON inspection(team_id,id);
