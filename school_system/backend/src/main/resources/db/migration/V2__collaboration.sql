-- Shared project/team boundary for module 3; management belongs to module A.
CREATE TABLE course_project (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES course(id),
 name VARCHAR(160) NOT NULL,
 status VARCHAR(24) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','IN_PROGRESS','ENDED','TERMINATED','ARCHIVED')),
 final_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
 demo_fixture BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE project_requirement (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES course_project(id),
 title VARCHAR(200) NOT NULL,
 description VARCHAR(2000) NOT NULL
);
CREATE TABLE project_team (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES course_project(id),
 name VARCHAR(120) NOT NULL,
 leader_id BIGINT NOT NULL REFERENCES app_user(id),
 revision BIGINT NOT NULL DEFAULT 0,
 UNIQUE(project_id,name)
);
CREATE TABLE project_team_member (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(team_id,user_id)
);
CREATE TABLE team_iteration (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 name VARCHAR(160) NOT NULL,
 goal VARCHAR(2000) NOT NULL,
 sequence_no INTEGER NOT NULL CHECK (sequence_no > 0),
 planned_start DATE NOT NULL,
 planned_end DATE NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'NOT_STARTED' CHECK(status IN ('NOT_STARTED','IN_PROGRESS','ENDED')),
 completion_summary VARCHAR(2000),
 leftovers VARCHAR(2000),
 started_at TIMESTAMP WITH TIME ZONE,
 ended_at TIMESTAMP WITH TIME ZONE,
 CHECK(planned_end >= planned_start),
 UNIQUE(team_id,sequence_no)
);
CREATE TABLE team_task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 original_iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 requirement_id BIGINT NOT NULL REFERENCES project_requirement(id),
 title VARCHAR(200) NOT NULL,
 description VARCHAR(2000) NOT NULL,
 assignee_id BIGINT NOT NULL REFERENCES app_user(id),
 planned_start DATE NOT NULL,
 planned_end DATE NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'NOT_STARTED' CHECK(status IN ('NOT_STARTED','IN_PROGRESS','COMPLETED')),
 progress_note VARCHAR(2000),
 completed_at TIMESTAMP WITH TIME ZONE,
 CHECK(planned_end >= planned_start)
);
CREATE INDEX idx_team_task_iteration ON team_task(team_id,iteration_id);
CREATE TABLE team_milestone (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 title VARCHAR(200) NOT NULL,
 target_date DATE NOT NULL,
 completion_criteria VARCHAR(2000) NOT NULL,
 completed BOOLEAN NOT NULL DEFAULT FALSE,
 completion_note VARCHAR(2000),
 completed_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE collaboration_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 actor_id BIGINT NOT NULL REFERENCES app_user(id),
 action VARCHAR(80) NOT NULL,
 object_type VARCHAR(24) NOT NULL,
 object_id BIGINT NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 before_data TEXT NOT NULL,
 after_data TEXT NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_collaboration_event_team ON collaboration_event(team_id,id);
