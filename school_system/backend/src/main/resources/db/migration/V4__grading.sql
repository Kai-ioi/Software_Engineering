-- Module D (module 7): teacher grading against a confirmed review version.
-- The rubric below is a self-contained placeholder until module A owns rubric configuration.
CREATE TABLE grading_rubric (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  name VARCHAR(160) NOT NULL,
  version_no INTEGER NOT NULL CHECK (version_no > 0),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_by BIGINT NOT NULL REFERENCES app_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(course_id, version_no)
);
CREATE TABLE grading_criterion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rubric_id BIGINT NOT NULL REFERENCES grading_rubric(id),
  name VARCHAR(160) NOT NULL,
  description VARCHAR(500) NOT NULL,
  max_score INTEGER NOT NULL CHECK (max_score > 0),
  sort_order INTEGER NOT NULL
);
CREATE INDEX idx_grading_criterion_rubric ON grading_criterion(rubric_id, sort_order);
CREATE TABLE grading_sheet (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rubric_id BIGINT NOT NULL REFERENCES grading_rubric(id),
  team_id BIGINT NOT NULL REFERENCES project_team(id),
  review_binding_id BIGINT NOT NULL REFERENCES submission_review_binding(id),
  status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','SUBMITTED')),
  graded_by BIGINT NOT NULL REFERENCES app_user(id),
  submitted_at TIMESTAMP WITH TIME ZONE,
  last_reason VARCHAR(2000),
  UNIQUE(team_id, rubric_id)
);
CREATE INDEX idx_grading_sheet_team ON grading_sheet(team_id);
CREATE TABLE grading_criterion_score (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sheet_id BIGINT NOT NULL REFERENCES grading_sheet(id),
  criterion_id BIGINT NOT NULL REFERENCES grading_criterion(id),
  score INTEGER NOT NULL CHECK (score >= 0),
  UNIQUE(sheet_id, criterion_id)
);
CREATE TABLE grading_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  team_id BIGINT NOT NULL REFERENCES project_team(id),
  actor_id BIGINT REFERENCES app_user(id),
  action VARCHAR(80) NOT NULL,
  object_id VARCHAR(100) NOT NULL,
  reason VARCHAR(2000) NOT NULL,
  before_data TEXT NOT NULL,
  after_data TEXT NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_grading_event_team ON grading_event(team_id, id);
