
CREATE TABLE expired_team_application (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES project_team_member(id),
 expired_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_expired_application_member ON expired_team_application(member_id,id);
CREATE TABLE assistant_team_scope (
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 PRIMARY KEY(team_id,user_id)
);
