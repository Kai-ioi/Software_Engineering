CREATE TABLE team (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES project(id),
  name VARCHAR(160) NOT NULL,
  leader_id BIGINT NOT NULL REFERENCES app_user(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_team_project ON team(project_id);

CREATE TABLE team_member (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES team(id),
  user_id BIGINT NOT NULL REFERENCES app_user(id),
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACTIVE', 'REJECTED', 'LEFT')),
  joined_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_team_user UNIQUE (team_id, user_id)
);
CREATE INDEX idx_member_team ON team_member(team_id, status);
CREATE INDEX idx_member_user ON team_member(user_id, status);
