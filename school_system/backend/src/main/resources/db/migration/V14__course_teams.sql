-- Course roster is fixed before selecting projects. Existing project delivery records retain their IDs.
ALTER TABLE course ADD COLUMN course_team_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE course ADD COLUMN required_projects INTEGER NOT NULL DEFAULT 2 CHECK(required_projects BETWEEN 1 AND 10);
CREATE TABLE course_team (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES course(id),
 name VARCHAR(160) NOT NULL,
 leader_id BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(course_id,name)
);
CREATE TABLE course_team_member (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES course_team(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 status VARCHAR(16) NOT NULL CHECK(status IN ('INVITED','ACTIVE','DECLINED','CANCELLED')),
 invited_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 answered_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(team_id,user_id)
);
CREATE INDEX idx_course_team_member_user ON course_team_member(user_id,status);
ALTER TABLE project_team ADD COLUMN course_team_id BIGINT REFERENCES course_team(id);
CREATE UNIQUE INDEX idx_course_project_enrollment ON project_team(course_team_id,project_id);
