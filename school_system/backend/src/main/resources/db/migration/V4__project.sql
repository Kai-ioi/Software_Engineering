CREATE TABLE project (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES course(id),
  title VARCHAR(160) NOT NULL,
  description VARCHAR(4000) NOT NULL,
  deadline TIMESTAMP WITH TIME ZONE,
  min_team_size INT NOT NULL,
  max_team_size INT NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED', 'ARCHIVED')),
  published_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_project_course ON project(course_id);

CREATE TABLE project_criterion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL REFERENCES project(id),
  name VARCHAR(160) NOT NULL,
  weight INT NOT NULL CHECK (weight >= 0 AND weight <= 100),
  description VARCHAR(1000)
);
CREATE INDEX idx_criterion_project ON project_criterion(project_id);