
ALTER TABLE course ADD COLUMN ended_at TIMESTAMP WITH TIME ZONE;
CREATE TABLE course_retention (
 course_id BIGINT PRIMARY KEY REFERENCES course(id),
 hold_reason VARCHAR(1000),
 approved_by BIGINT REFERENCES app_user(id),
 approved_at TIMESTAMP WITH TIME ZONE,
 executed_by BIGINT REFERENCES app_user(id),
 executed_at TIMESTAMP WITH TIME ZONE,
 manifest TEXT
);
CREATE TABLE retention_file (
 course_id BIGINT NOT NULL REFERENCES course(id),
 file_id UUID NOT NULL,
 removed BOOLEAN NOT NULL DEFAULT FALSE,
 error VARCHAR(240),
 PRIMARY KEY(course_id,file_id)
);
CREATE TABLE retention_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id BIGINT NOT NULL REFERENCES course(id),
 actor_id BIGINT NOT NULL REFERENCES app_user(id),
 action VARCHAR(30) NOT NULL,
 detail VARCHAR(2000) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
