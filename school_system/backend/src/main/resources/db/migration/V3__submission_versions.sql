CREATE TABLE submission_material (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 kind VARCHAR(8) NOT NULL CHECK(kind IN ('FILE','LINK')),
 file_id UUID REFERENCES stored_file(id),
 title VARCHAR(240) NOT NULL,
 url VARCHAR(2000),
 code_link BOOLEAN NOT NULL DEFAULT FALSE,
 code_ref VARCHAR(200),
 created_by BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 CHECK((kind='FILE' AND file_id IS NOT NULL AND url IS NULL) OR (kind='LINK' AND file_id IS NULL AND url IS NOT NULL))
);
CREATE INDEX idx_submission_material_team ON submission_material(team_id,iteration_id,active);
CREATE TABLE submission_package (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 current_version_id BIGINT,
 UNIQUE(team_id,iteration_id)
);
CREATE TABLE submission_extension_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 requested_by BIGINT NOT NULL REFERENCES app_user(id),
 reason VARCHAR(2000) NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
 resolved_by BIGINT REFERENCES app_user(id),
 resolved_at TIMESTAMP WITH TIME ZONE,
 resolution VARCHAR(2000)
);
CREATE TABLE submission_extension (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 request_id BIGINT REFERENCES submission_extension_request(id),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
 ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 granted_by BIGINT NOT NULL REFERENCES app_user(id),
 granted_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK(ends_at>starts_at)
);
CREATE TABLE submission_version (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 package_id BIGINT NOT NULL REFERENCES submission_package(id),
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 iteration_id BIGINT NOT NULL REFERENCES team_iteration(id),
 version_no INTEGER NOT NULL CHECK(version_no>0),
 submitted_by BIGINT NOT NULL REFERENCES app_user(id),
 summary VARCHAR(2000) NOT NULL,
 accepted_at TIMESTAMP WITH TIME ZONE NOT NULL,
 deadline_snapshot TIMESTAMP WITH TIME ZONE NOT NULL,
 late BOOLEAN NOT NULL,
 extension_id BIGINT REFERENCES submission_extension(id),
 total_bytes BIGINT NOT NULL CHECK(total_bytes>=0 AND total_bytes<=209715200),
 request_key UUID NOT NULL,
 payload_hash VARCHAR(64) NOT NULL,
 receipt_code VARCHAR(100) NOT NULL UNIQUE,
 UNIQUE(package_id,version_no),
 UNIQUE(team_id,request_key)
);
ALTER TABLE submission_package ADD CONSTRAINT fk_package_current_version FOREIGN KEY(current_version_id) REFERENCES submission_version(id);
CREATE TABLE submission_version_material (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version_id BIGINT NOT NULL REFERENCES submission_version(id),
 kind VARCHAR(8) NOT NULL CHECK(kind IN ('FILE','LINK')),
 file_id UUID REFERENCES stored_file(id),
 title VARCHAR(240) NOT NULL,
 url VARCHAR(2000),
 code_link BOOLEAN NOT NULL,
 code_ref VARCHAR(200),
 size_bytes BIGINT NOT NULL,
 sha256 VARCHAR(64)
);
CREATE TABLE submission_review_binding (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 version_id BIGINT NOT NULL REFERENCES submission_version(id),
 confirmed_by BIGINT NOT NULL REFERENCES app_user(id),
 confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 reassessment_required BOOLEAN NOT NULL DEFAULT FALSE
);
-- Module C grants access to a specific binding, never to the mutable latest version.
CREATE TABLE submission_review_access (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 binding_id BIGINT NOT NULL REFERENCES submission_review_binding(id),
 reviewer_id BIGINT NOT NULL REFERENCES app_user(id),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(binding_id,reviewer_id)
);
CREATE TABLE team_delivery (
 team_id BIGINT PRIMARY KEY REFERENCES project_team(id),
 final_version_id BIGINT REFERENCES submission_version(id),
 selected_by BIGINT REFERENCES app_user(id),
 selected_at TIMESTAMP WITH TIME ZONE,
 frozen_at TIMESTAMP WITH TIME ZONE,
 frozen_deadline TIMESTAMP WITH TIME ZONE,
 review_binding_id BIGINT REFERENCES submission_review_binding(id)
);
CREATE TABLE submission_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 actor_id BIGINT REFERENCES app_user(id),
 action VARCHAR(80) NOT NULL,
 object_id VARCHAR(100) NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 before_data TEXT NOT NULL,
 after_data TEXT NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 notify_team BOOLEAN NOT NULL DEFAULT FALSE,
 notify_teachers BOOLEAN NOT NULL DEFAULT FALSE,
 notice_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 notice_attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_submission_event_team ON submission_event(team_id,id);
CREATE TABLE submission_notice (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id BIGINT NOT NULL REFERENCES submission_event(id),
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 team_id BIGINT NOT NULL REFERENCES project_team(id),
 title VARCHAR(240) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 read_at TIMESTAMP WITH TIME ZONE,
 UNIQUE(event_id,user_id)
);
